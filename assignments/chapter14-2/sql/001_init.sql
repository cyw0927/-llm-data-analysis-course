-- Chapter 14-2: Supabase PostgreSQL - 최초 1회 / 재실행 가능 기초 DDL
-- 외부 API의 미검증 데이터를 DB에 삽입하기 전에 Seed 검증을 완료한다.
-- Dashboard = Publishable Key + RLS SELECT; Make = 서버 측 Secret Key.

create table if not exists public.regions (
    region_code text primary key,
    region_name text not null unique,
    center_lat double precision,
    center_lng double precision,
    created_at timestamptz not null default now()
);

create table if not exists public.naver_trend (
    id bigint generated by default as identity primary key,
    reference_date date not null,
    keyword text not null,
    ratio numeric not null check (ratio between 0 and 100),
    collected_at timestamptz not null default now(),
    unique (reference_date, keyword)
);

create table if not exists public.tourism_demand (
    id bigint generated by default as identity primary key,
    reference_date date not null,
    region_code text not null,
    stay_strength numeric,
    consumption_strength numeric,
    collected_at timestamptz not null default now(),
    unique (reference_date, region_code)
);

create table if not exists public.local_places (
    id bigint generated by default as identity primary key,
    place_key text not null unique,
    region_code text,
    search_category text not null,
    name text not null,
    category text,
    address text,
    road_address text,
    longitude double precision,
    latitude double precision,
    source_link text,
    collected_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.ai_region_analysis (
    id bigint generated by default as identity primary key,
    analysis_date date not null,
    region_code text not null,
    summary text not null,
    limitations text,
    llm_provider text,
    model_name text,
    created_at timestamptz not null default now(),
    unique (analysis_date, region_code)
);

create table if not exists public.collection_runs (
    run_id text primary key,
    source text not null,
    started_at timestamptz not null,
    finished_at timestamptz,
    status text not null,
    row_count integer not null default 0,
    error_message text,
    created_at timestamptz not null default now()
);

create index if not exists idx_tourism_demand_date_region
    on public.tourism_demand (reference_date desc, region_code);
create index if not exists idx_naver_trend_date
    on public.naver_trend (reference_date desc);
create index if not exists idx_local_places_region_category
    on public.local_places (region_code, search_category);
create index if not exists idx_ai_region_analysis_date
    on public.ai_region_analysis (analysis_date desc);

-- Dashboard 대상 5개 테이블만 anon/authenticated 공개 읽기. collection_runs는 내부 전용이며 쓰기 정책은 만들지 않음.
alter table public.regions enable row level security;
alter table public.naver_trend enable row level security;
alter table public.tourism_demand enable row level security;
alter table public.local_places enable row level security;
alter table public.ai_region_analysis enable row level security;
alter table public.collection_runs enable row level security;

-- 재실행 시 이미 있는 동일 정책을 삭제하지 않고 보존
do $policies$
declare t text;
begin
    foreach t in array array[
      'regions', 'naver_trend', 'tourism_demand',
      'local_places', 'ai_region_analysis'
    ]
    loop
        if not exists (
            select 1 from pg_policies
            where schemaname = 'public' and tablename = t
              and policyname = 'public read ' || t
        ) then
            execute format(
              'create policy %I on public.%I for select to anon, authenticated using (true)',
              'public read ' || t, t
            );
        end if;
    end loop;
end
$policies$;

-- 이전 버전의 동일 migration을 다시 적용하더라도 실행 로그는 공개되지 않도록 회수한다.
drop policy if exists "public read collection_runs" on public.collection_runs;
revoke all on public.collection_runs from public, anon, authenticated;

grant usage on schema public to anon, authenticated;
grant select on public.regions, public.naver_trend, public.tourism_demand,
  public.local_places, public.ai_region_analysis
  to anon, authenticated;

-- collection_runs는 Make의 서버 측 Secret Key를 사용하는 내부 기록이다.
-- error_message에는 API key, 인증 헤더, 호출 URL의 serviceKey 등 비밀정보를 저장하지 않는다.

-- 수업의 Supabase SQL/View 활용 연습: 최신 관측값의 기간 차이를 감추지 않는다.
create or replace view public.latest_tourism_demand
with (security_invoker = true) as
select t.reference_date, t.region_code,
       coalesce(r.region_name, t.region_code) as region_name,
       t.stay_strength, t.consumption_strength
from public.tourism_demand t
left join public.regions r on r.region_code = t.region_code
where t.reference_date = (select max(reference_date) from public.tourism_demand);

create or replace view public.latest_naver_trend
with (security_invoker = true) as
select n.reference_date, n.keyword, n.ratio
from public.naver_trend n
where n.reference_date = (select max(reference_date) from public.naver_trend);

grant select on public.latest_tourism_demand, public.latest_naver_trend
to anon, authenticated;

